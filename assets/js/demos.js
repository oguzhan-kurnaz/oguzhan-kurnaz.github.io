  // ---------- Audio helpers ----------
  async function decodeTo(blob, sampleRate, maxSeconds) {
    const buf = await blob.arrayBuffer();
    const ctx = new (window.AudioContext || window.webkitAudioContext)();
    let decoded;
    try { decoded = await ctx.decodeAudioData(buf); } finally { ctx.close(); }
    const dur = Math.min(decoded.duration, maxSeconds);
    const off = new OfflineAudioContext(1, Math.max(1, Math.ceil(dur * sampleRate)), sampleRate);
    const src = off.createBufferSource();
    src.buffer = decoded;
    src.connect(off.destination);
    src.start(0);
    const pcm = (await off.startRendering()).getChannelData(0);
    return { pcm, blob: encodeWav(pcm, sampleRate), duration: dur, sr: sampleRate };
  }

  function encodeWav(samples, sr) {
    const view = new DataView(new ArrayBuffer(44 + samples.length * 2));
    const w = (o, s) => { for (let i = 0; i < s.length; i++) view.setUint8(o + i, s.charCodeAt(i)); };
    w(0, "RIFF"); view.setUint32(4, 36 + samples.length * 2, true); w(8, "WAVE");
    w(12, "fmt "); view.setUint32(16, 16, true); view.setUint16(20, 1, true); view.setUint16(22, 1, true);
    view.setUint32(24, sr, true); view.setUint32(28, sr * 2, true); view.setUint16(32, 2, true); view.setUint16(34, 16, true);
    w(36, "data"); view.setUint32(40, samples.length * 2, true);
    for (let i = 0; i < samples.length; i++) {
      const s = Math.max(-1, Math.min(1, samples[i]));
      view.setInt16(44 + i * 2, s < 0 ? s * 0x8000 : s * 0x7fff, true);
    }
    return new Blob([view], { type: "audio/wav" });
  }

  // ---------- Record / upload slots ----------
  function buildSlot(el) {
    const key = el.dataset.slot, sr = +el.dataset.sr, max = +el.dataset.max;
    el.insertAdjacentHTML("beforeend", `
      <div class="rec-row">
        <button type="button" class="sbtn rec"><span class="dot"></span><span data-i18n="d.rec">${t("d.rec")}</span></button>
        <label class="sbtn"><input type="file" accept="audio/*"><span data-i18n="d.upload">${t("d.upload")}</span></label>
        <span class="timer"></span>
      </div>
      <div class="clip"></div>`);
    const recBtn = el.querySelector(".rec"), recLabel = recBtn.querySelector("[data-i18n]");
    const timer = el.querySelector(".timer"), clipBox = el.querySelector(".clip"), file = el.querySelector("input[type=file]");
    let recorder = null, tick = null;
    const slot = { clip: null };

    slot.set = async (blob, note) => {
      try {
        slot.clip = await decodeTo(blob, sr, max);
      } catch (e) {
        slot.clip = null;
        clipBox.innerHTML = `<p class="status err">${t("d.decode")}</p>`;
        return;
      }
      const url = URL.createObjectURL(slot.clip.blob);
      clipBox.innerHTML = `<audio controls src="${url}"></audio>
        <div class="meta">${slot.clip.duration.toFixed(1)} s · ${sr / 1000} kHz${note ? ` · ${esc(note)}` : ""} · <a href="#" class="rm" data-i18n="d.remove">${t("d.remove")}</a></div>`;
      clipBox.querySelector(".rm").addEventListener("click", (ev) => { ev.preventDefault(); slot.clip = null; clipBox.innerHTML = ""; });
    };

    const stop = () => { if (recorder && recorder.state !== "inactive") recorder.stop(); };

    recBtn.addEventListener("click", async () => {
      if (recorder && recorder.state === "recording") return stop();
      let stream;
      try {
        stream = await navigator.mediaDevices.getUserMedia({ audio: { channelCount: 1, echoCancellation: false, noiseSuppression: false, autoGainControl: true } });
      } catch (e) {
        clipBox.innerHTML = `<p class="status err">${t("d.mic")}</p>`;
        return;
      }
      const chunks = [];
      recorder = new MediaRecorder(stream);
      recorder.ondataavailable = (e) => e.data.size && chunks.push(e.data);
      recorder.onstop = () => {
        clearInterval(tick); timer.textContent = "";
        stream.getTracks().forEach((tr) => tr.stop());
        recBtn.classList.remove("live"); recLabel.dataset.i18n = "d.rec"; recLabel.textContent = t("d.rec");
        slot.set(new Blob(chunks, { type: recorder.mimeType }));
      };
      recorder.start();
      const t0 = Date.now();
      recBtn.classList.add("live"); recLabel.dataset.i18n = "d.stop"; recLabel.textContent = t("d.stop");
      tick = setInterval(() => {
        const s = (Date.now() - t0) / 1000;
        timer.textContent = `${s.toFixed(1)} / ${max} s`;
        if (s >= max) stop();
      }, 100);
    });

    file.addEventListener("change", () => { if (file.files[0]) slot.set(file.files[0]); file.value = ""; });
    slots[key] = slot;
  }

