  // ---------- Model worker ----------
  let worker = null, seq = 0;
  const pending = {};
  function callWorker(task, payload, onProgress) {
    if (!worker) {
      worker = new Worker("assets/js/lab-worker.js", { type: "module" });
      worker.onmessage = (e) => {
        const m = e.data, p = pending[m.id];
        if (!p) return;
        if (m.type === "progress") p.onProgress(m);
        else { delete pending[m.id]; m.type === "result" ? p.resolve(m.result) : p.reject(new Error(m.message)); }
      };
      worker.onerror = (e) => {
        for (const id of Object.keys(pending)) { pending[id].reject(new Error(e.message || "Worker error")); delete pending[id]; }
      };
    }
    const id = ++seq;
    return new Promise((resolve, reject) => {
      pending[id] = { resolve, reject, onProgress };
      worker.postMessage({ id, task, ...payload });
    });
  }

